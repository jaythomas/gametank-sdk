#!/usr/bin/env node
//
// Generates gain.asm: the firmware's per-volume-level gain pages.
//
// Run from this directory:
//     node gen_gain_tables.js > gain.asm
//
// --- Why these tables exist -------------------------------------------------
//
// The audio ISR scales a voice's sample by its volume with a single indexed
// load, `lda (GAINPTR),y`, where Y is the wavetable sample with its low two
// bits cleared (`and #$FC`) and GAINPTR points at the entry for that voice's
// current volume. A whole multiply therefore costs 9 cycles instead of the ~44
// the old sine-difference scheme needed, and the gain is genuinely linear, so
// samples are no longer waveshaped by a cosine on their way to the DAC.
//
// --- Layout: four levels interleaved per 256-byte block ----------------------
//
// A level needs only 64 entries (the sample's top six bits), so four levels
// share one 256-byte block, interleaved: level L = 4*b + k keeps its entry for
// index i at block b, offset 4*i + k. Y is always a multiple of 4, and GAINPTR
// is the block's address plus k, so the load lands on the right level's entry.
// The largest offset is 4*63 + 3 = 255, so the load never crosses a page.
//
// Levels therefore cost nothing in the ISR - they cost only ARAM, 256 bytes per
// four of them, and all six blocks the 4KB can spare are now in use.
//
// --- Encoding ---------------------------------------------------------------
//
// Entries are stored in units of 1/4 DAC LSB so that seven voices can be summed
// exactly, in an 11-bit accumulator, and quantized only once at the output. Two
// fractional bits is the most that fits while keeping an entry one byte wide.
//
//     entry[v][i] = round(4 * G(v) * (s - 127.5)) + ACC_BIAS,  s = 4*i + 1.5
//
// i is the 6-bit sample index and s the middle of the four sample values it
// stands for, so quantizing the sample adds no DC offset. At full gain a voice
// spans +/-31.5 DAC LSBs and each index step is one LSB, so the 6-bit index
// costs no more than the DAC's own rounding; at lower gains it costs less.
// ACC_BIAS keeps entries unsigned so the ISR can accumulate with plain ADC; the
// ISR starts its accumulator at -7*ACC_BIAS to cancel it back out.
//
// --- Headroom ---------------------------------------------------------------
//
// G is capped at 127/512, i.e. a quarter of full scale, so four voices at
// maximum volume reach the DAC's full swing. Seven loud voices can overshoot,
// which the ISR resolves by hard-saturating the final sum. Dividing by seven
// instead would make overflow impossible but would cost ~8.5dB that
// uncorrelated voices never actually use.

const LEVELS = 24; // volume 0..23
const INDICES = 64; // 6-bit sample index
const INTERLEAVE = 4; // levels sharing one 256-byte block
const ACC_BIAS = 128;
const G_MAX = 127 / 512; // quarter of full scale, clamped to a signed byte
const STEP_DB_TOP = 1.3; // spacing between adjacent levels at the loud end
const STEP_DB_BOTTOM = 3.5; // spacing between levels 1 and 2
const FLAT_STEPS = 11; // steps from the top that keep the loud-end spacing

/// dB below full volume of a level. The top levels are evenly spaced; below
/// them the spacing widens linearly so level 1 sits near -42dB, quiet enough
/// that fading to silence is not an audible cliff. An even 1.3dB all the way
/// down would stop at -29dB, where the last few levels are barely
/// distinguishable and the drop to 0 is abrupt.
function dbBelowMax(level) {
  let db = 0;
  for (let k = 1; k <= LEVELS - 1 - level; k++) {
    const t = Math.max(0, (k - FLAT_STEPS) / (LEVELS - 1 - FLAT_STEPS));
    db += STEP_DB_TOP + (STEP_DB_BOTTOM - STEP_DB_TOP) * t;
  }
  return db;
}

/// Linear gain for a volume level. Level 0 is true silence.
function gainFor(level) {
  if (level === 0) return 0;
  return G_MAX * Math.pow(10, -dbBelowMax(level) / 20);
}

function levelEntries(level) {
  const g = gainFor(level);
  const bytes = [];
  for (let i = 0; i < INDICES; i++) {
    const scaled = Math.round(4 * g * (4 * i + 1.5 - 127.5));
    const clamped = Math.max(-ACC_BIAS, Math.min(127, scaled));
    bytes.push(clamped + ACC_BIAS);
  }
  return bytes;
}

const out = [];
out.push('; Generated by gen_gain_tables.js - do not edit by hand.');
out.push(';');
out.push(`; ${LEVELS} volume levels, ${INTERLEAVE} interleaved per 256-byte block.`);
out.push('; Level L = 4*b + k: entry for index i (= sample >> 2) is at block b, offset 4*i + k.');
out.push(`; entry = round(4 * G(v) * (4*i + 1.5 - 127.5)) + ${ACC_BIAS}, in units of 1/4 DAC LSB.`);
out.push(`; G(${LEVELS - 1}) = ${G_MAX.toFixed(6)} (quarter scale); ${STEP_DB_TOP}dB per step at the top widening to ${STEP_DB_BOTTOM}dB at the bottom; G(0) = 0.`);
out.push(';');
out.push('; Peak deviation from silence, in whole DAC LSBs, per level:');
for (let v = 0; v < LEVELS; v++) {
  const peak = (4 * gainFor(v) * 126) / 4;
  out.push(`;   level ${v}: +/-${peak.toFixed(2)}`);
}
out.push('');
out.push('.section .const.gain, "a"');
out.push('.align 256');
out.push('.global gain_table');
out.push('gain_table:');

const levels = Array.from({ length: LEVELS }, (_, v) => levelEntries(v));
for (let b = 0; b < LEVELS / INTERLEAVE; b++) {
  out.push(`; --- block ${b}: levels ${b * INTERLEAVE}..${b * INTERLEAVE + INTERLEAVE - 1} ---`);
  const block = [];
  for (let i = 0; i < INDICES; i++) {
    for (let k = 0; k < INTERLEAVE; k++) block.push(levels[b * INTERLEAVE + k][i]);
  }
  for (let row = 0; row < block.length; row += 16) {
    const chunk = block
      .slice(row, row + 16)
      .map((x) => '0x' + x.toString(16).padStart(2, '0'));
    out.push('\t.byte ' + chunk.join(', '));
  }
}

console.log(out.join('\n'));
